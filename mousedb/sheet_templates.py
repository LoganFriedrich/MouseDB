INFO_SHEET = "_template"
_INFO_KEYS = ("reference_cohort", "model_animal", "made_from", "made_at")


# ---------------------------------------------------------------------------
# reading a workbook's structure
# ---------------------------------------------------------------------------

def _id_regex(cohort_id: str) -> re.Pattern:
    """Subject ids of one cohort: '<COHORT>_NN' (PROJA_05 -> PROJA_05_01 ...)."""
    return re.compile(r"^%s_(\d{2})$" % re.escape(cohort_id))


def _is_formula(v) -> bool:
    return isinstance(v, str) and v.startswith("=")


def _is_date(v) -> bool:
    return isinstance(v, (datetime, date, time))


def _blank(v) -> bool:
    return v is None or (isinstance(v, str) and not v.strip())


@dataclass
class Group:
    """One group of animal rows: {animal: [rows in order]}, animals in order."""
    rows: "OrderedDict[str, List[int]]" = field(default_factory=OrderedDict)


@dataclass
class Table:
    """One table of a tab: a run of columns between empty columns."""
    first_col: int
    last_col: int
    id_col: Optional[int] = None
    header_rows: List[int] = field(default_factory=list)
    # the sequence after the header: ("group", Group) or ("plain", row)
    sequence: list = field(default_factory=list)
    loose_cols: List[int] = field(default_factory=list)

    @property
    def groups(self) -> List[Group]:
        return [x for kind, x in self.sequence if kind == "group"]


def _used_columns(ws) -> set:
    used = set()
    for row in ws.iter_rows():
        for c in row:
            if not _blank(c.value):
                used.add(c.column)
    return used


def _tables(ws, ids: re.Pattern) -> List[Table]:
    """Split a tab into side-by-side tables and read each one's rows."""
    used = _used_columns(ws)
    if not used:
        return []
    runs, start = [], None
    for c in range(1, max(used) + 2):
        if c in used and start is None:
            start = c
        elif c not in used and start is not None:
            runs.append((start, c - 1))
            start = None
    return [_read_table(ws, a, b, ids) for a, b in runs]


def _animal_at(ws, r, c, ids) -> Optional[str]:
    v = ws.cell(r, c).value
    return v.strip() if isinstance(v, str) and ids.match(v.strip()) else None


def _read_table(ws, first_col, last_col, ids) -> Table:
    t = Table(first_col, last_col)
    best, best_n = None, 0
    for c in range(first_col, last_col + 1):
        n = sum(1 for r in range(1, ws.max_row + 1) if _animal_at(ws, r, c, ids))
        if n > best_n:
            best, best_n = c, n
    if best is None or best_n < 2:
        return t                                   # no animal column: a fixed table
    t.id_col = best
    animal_rows = [r for r in range(1, ws.max_row + 1) if _animal_at(ws, r, best, ids)]
    first = animal_rows[0]
    t.header_rows = [r for r in range(1, first)
                     if any(not _blank(ws.cell(r, c).value) for c in range(first_col, last_col + 1))]
    last = max(r for r in range(1, ws.max_row + 1)
               if any(not _blank(ws.cell(r, c).value) for c in range(first_col, last_col + 1)))
    group, prev = None, None
    for r in range(first, last + 1):
        a = _animal_at(ws, r, best, ids)
        if a is None:
            if any(not _blank(ws.cell(r, c).value) for c in range(first_col, last_col + 1)):
                t.sequence.append(("plain", r))
                group, prev = None, None
            continue
        new_group = group is None or (a != prev and (a in group.rows))
        if new_group:
            group = Group()
            t.sequence.append(("group", group))
        group.rows.setdefault(a, []).append(r)
        prev = a
    # headerless columns that only a few animal rows use: loose cells
    for c in range(first_col, last_col + 1):
        if c == best or any(not _blank(ws.cell(h, c).value) for h in t.header_rows):
            continue
        n = sum(1 for r in animal_rows if not _blank(ws.cell(r, c).value))
        if 0 < n < max(2, len(animal_rows) // 2):
            t.loose_cols.append(c)
    return t


def _workbook_tables(wb, ids) -> Dict[str, List[Table]]:
    return {ws.title: _tables(ws, ids) for ws in wb.worksheets if ws.title != INFO_SHEET}


def _row_counts(tables: Dict[str, List[Table]]) -> Counter:
    n = Counter()
    for ts in tables.values():
        for t in ts:
            for g in t.groups:
                for a, rows in g.rows.items():
                    n[a] += len(rows)
    return n


