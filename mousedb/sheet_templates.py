"""New cohort tracking workbooks, built from the project's own template.

WHY THIS EXISTS
---------------
A new cohort's tracking workbook used to be generated by code that held one
lab's whole protocol (tabs, columns, schedule, formulas) as constants. The
workbooks the lab actually works in drifted from it, so a "new sheet" matched
none of them, and a second project could get no sheet at all (2026-10-29: its
workbooks were made by hand and their tabs did not match the first project's).

Now a project's format lives in a TEMPLATE: an ordinary workbook, made from a
cohort sheet the lab is happy with, that anyone can open in Excel and change.
Whatever the template looks like, a new sheet looks like.

THE TEMPLATE
------------
``make_template`` copies a reference cohort's workbook and clears what was
measured, keeping the format:

- every tab, column, header, formula, style, column width and frozen pane;
- the animals' rows (their ids stay; the builder replaces them);
- SKELETON columns -- typed values that are the same for every animal on a
  given day and change from day to day (the phase, the tray), i.e. the
  schedule laid out ahead of time;
- in tabs with no animal column (planning, calculations), the typed values.

It clears every other typed value in an animal's row (scores, weights, sex,
notes ...), and EVERY date anywhere: a date is never a constant. A value that
is the same for every animal of a one-row-per-animal tab (an anaesthetic, a
target level) is cleared too, unless listed in ``keep`` -- it may equally be
"the same for everyone so far" (a survival column before anyone died); the
report lists each such column so a person can decide. A sheet named
``_template`` records which cohort the template came from and which animal's
rows are the model (the animal with the most rows: the one that went through
every part of the schedule).

THE BUILDER
-----------
``build_sheet`` reads the template's own structure. In each tab, side-by-side
tables (separated by an empty column) are handled separately. In a table with
an animal column, the rows before the first animal are its header; after that
the animal rows come in GROUPS (a day: every animal in turn, each with one or
more rows -- one per tray, say), possibly with plain rows between groups (a
second block's header). The builder writes, for every group, the model
animal's rows once per new animal, in the new animals' order, and replaces the
ids. A tab's group where the model animal has no row is dropped (reported).

Formulas are re-pointed, not copied blindly:

- a reference to the model animal's row (in this tab or another) points at the
  SAME new animal's copy of that row -- so "this row's weight / this animal's
  baseline weight" stays this animal's;
- a range from one animal to another within a group (an average over every
  animal on a day) widens to the first and last new animal of that group;
- a reference to a header row, a plain row or a whole column keeps its place.

Cells in a headerless column that only a few animal rows use (a "Mean" and
"SD" beside a table) stay where they are, written once, not once per animal.

Anything the builder cannot re-point is left as it is and listed in the
report, never guessed.

Nothing here writes into the sheets folder except through the no-clobber save
(``make_sheets._save_workbook_no_clobber``): a new workbook never replaces or
sits beside an existing one for the cohort.

ASCII-only output (Windows consoles).
"""
