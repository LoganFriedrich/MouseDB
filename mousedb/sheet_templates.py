@dataclass
class Report:
    lines: List[str] = field(default_factory=list)

    def add(self, text: str) -> None:
        self.lines.append(text)

    def text(self) -> str:
        return "\n".join(self.lines) + "\n"


def _skeleton_columns(ws, t: Table, model: str) -> Dict[int, int]:
    """Typed columns of an animal table that hold the SCHEDULE, as
    {column: number of groups where the animals disagreed}.

    A schedule column is filled on at least 90% of the model animal's rows; in
    at least three quarters of the groups of two or more animals, every animal
    has the same value at the same row of its rows; and the value is not the
    same in every group. Dates never count. WHY these conditions: a measurement
    can match by chance (two animals with the same total) and a column filled
    only now and then is not a plan -- but a sheet that has been worked in
    splits its animals later on (some go on to one phase, the rest to
    another), so a few groups disagreeing must not hide the schedule. Where
    they disagree, the model animal's own value is what the template keeps."""
    groups = [g for g in t.groups if len(g.rows) >= 2]
    if len(groups) < 2:
        return {}
    model_rows = [r for g in t.groups for r in g.rows.get(model, [])]
    out: Dict[int, int] = {}
    for c in range(t.first_col, t.last_col + 1):
        if c == t.id_col or c in t.loose_cols or not model_rows:
            continue
        filled = [r for r in model_rows
                  if not _blank(ws.cell(r, c).value) and not _is_formula(ws.cell(r, c).value)]
        if len(filled) < 0.9 * len(model_rows):
            continue
        if any(_is_date(ws.cell(r, c).value) for r in filled):
            continue
        per_group, disagree = [], 0
        for g in groups:
            seen: Dict[int, set] = {}
            for rows in g.rows.values():
                for k, r in enumerate(rows):
                    v = ws.cell(r, c).value
                    if not _blank(v) and not _is_formula(v):
                        seen.setdefault(k, set()).add(v)
            if any(len(vs) > 1 for vs in seen.values()):
                disagree += 1
            else:
                per_group.append(tuple(sorted((k, str(next(iter(vs)))) for k, vs in seen.items())))
        if disagree <= len(groups) / 4 and len(set(per_group)) > 1:
            out[c] = disagree
    return out


def make_template(reference, cohort_id: str, out, keep: Optional[Dict[str, Sequence[str]]] = None) -> Report:
    """Write a template made from ``reference`` (a cohort's workbook) to ``out``
    and return the report of what was kept and cleared. ``keep`` maps a tab
    name to header names whose values are kept although every animal had the
    same one (see the module docstring). Never writes over ``out``."""
    reference, out = Path(reference), Path(out)
    if out.exists():
        raise FileExistsError("%s already exists; a template is never written over" % out)
    keep = {k: set(v) for k, v in (keep or {}).items()}
    ids = _id_regex(cohort_id)
    wb = openpyxl.load_workbook(reference)
    tables = _workbook_tables(wb, ids)
    counts = _row_counts(tables)
    if not counts:
        raise ValueError("no animal of %s found in %s" % (cohort_id, reference.name))
    model = max(sorted(counts), key=lambda a: counts[a])
    rep = Report()
    rep.add("Template for %s, made from %s" % (cohort_id.split("_")[0], reference.name))
    rep.add("Model animal: %s (%d rows; the animal with the most rows)" % (model, counts[model]))
    rep.add("")
    for ws in wb.worksheets:
        ts = tables.get(ws.title, [])
        cleared_dates = 0
        if not any(t.id_col for t in ts):
            for row in ws.iter_rows():
                for c in row:
                    if _is_date(c.value):
                        c.value = None
                        cleared_dates += 1
            rep.add("[%s] no animal rows: kept as is%s" % (
                ws.title, ", %d dates cleared" % cleared_dates if cleared_dates else ""))
            continue
        for t in ts:
            if t.id_col is None:
                for r in range(1, ws.max_row + 1):
                    for c in range(t.first_col, t.last_col + 1):
                        if _is_date(ws.cell(r, c).value):
                            ws.cell(r, c).value = None
                continue
            skel = _skeleton_columns(ws, t, model)
            headers = {c: " ".join(str(ws.cell(h, c).value) for h in t.header_rows
                                   if not _blank(ws.cell(h, c).value)) or get_column_letter(c)
                       for c in range(t.first_col, t.last_col + 1)}
            kept_const, same_for_all = [], []
            one_group = len(t.groups) == 1
            for c in range(t.first_col, t.last_col + 1):
                if c == t.id_col or c in skel or c in t.loose_cols:
                    continue
                vals = [ws.cell(r, c).value for g in t.groups for rows in g.rows.values() for r in rows]
                typed = [v for v in vals if not _blank(v) and not _is_formula(v)]
                if one_group and typed and len(set(map(str, typed))) == 1 and not _is_date(typed[0]):
                    if typed[0] == cohort_id:
                        kept_const.append("%s (the cohort id)" % headers[c])
                        continue
                    if headers[c] in keep.get(ws.title, ()):
                        kept_const.append("%s = %r" % (headers[c], typed[0]))
                        continue
                    same_for_all.append("%s = %r" % (headers[c], typed[0]))
                for g in t.groups:
                    for rows in g.rows.values():
                        for r in rows:
                            if not _is_formula(ws.cell(r, c).value):
                                ws.cell(r, c).value = None
            for r in t.header_rows:
                for c in range(t.first_col, t.last_col + 1):
                    if _is_date(ws.cell(r, c).value):
                        ws.cell(r, c).value = None
            for kind, x in t.sequence:
                if kind == "plain":
                    for c in range(t.first_col, t.last_col + 1):
                        if _is_date(ws.cell(x, c).value):
                            ws.cell(x, c).value = None
            where = "columns %s-%s" % (get_column_letter(t.first_col), get_column_letter(t.last_col))
            n_model = sum(len(g.rows.get(model, [])) for g in t.groups)
            dropped = sum(1 for g in t.groups if model not in g.rows)
            rep.add("[%s] %s: %d group(s) of animal rows, %d row(s) for the model animal%s" % (
                ws.title, where, len(t.groups), n_model,
                "; %d group(s) without the model animal are left out of new sheets" % dropped if dropped else ""))
            if skel:
                rep.add("    schedule kept: %s" % ", ".join(
                    headers[c] + (" (animals disagreed in %d group(s); the model animal's value kept)"
                                  % skel[c] if skel[c] else "") for c in sorted(skel)))
            if kept_const:
                rep.add("    kept for every animal: %s" % "; ".join(kept_const))
            if same_for_all:
                rep.add("    CLEARED although the same for every animal (keep with --keep): %s"
                        % "; ".join(same_for_all))
            if t.loose_cols:
                rep.add("    cells beside the table, written once: columns %s"
                        % ", ".join(get_column_letter(c) for c in t.loose_cols))
    for ws in wb.worksheets:
        # A frozen pane far down the sheet is where someone last scrolled to,
        # not part of the format: a new sheet freezes only its header rows.
        ts = tables.get(ws.title, [])
        first_data = min(((t.header_rows[-1] if t.header_rows else 0) + 1 for t in ts if t.id_col),
                         default=None)
        if ws.freeze_panes and first_data:
            row = int(re.sub(r"[A-Z]", "", ws.freeze_panes) or 1)
            if row > first_data:
                rep.add("[%s] frozen pane at %s moved to the first animal row (%d)"
                        % (ws.title, ws.freeze_panes, first_data))
                ws.freeze_panes = "A%d" % first_data
    for ws in wb.worksheets:
        _drop_stray_colour_rules(ws, tables.get(ws.title, []), rep)
    info = wb.create_sheet(INFO_SHEET)
    info.append(["key", "value"])
    info.append(["reference_cohort", cohort_id])
    info.append(["model_animal", model])
    info.append(["made_from", reference.name])
    info.append(["made_at", datetime.now().isoformat(timespec="seconds")])
    info.sheet_state = "hidden"
    out.parent.mkdir(parents=True, exist_ok=True)
    from .cohort_tools.make_sheets import _save_workbook_no_clobber
    _save_workbook_no_clobber(wb, out)
    return rep


def _drop_stray_colour_rules(ws, ts: List[Table], rep: Report) -> None:
    """Colour rules a person put on particular cells of a worked-in sheet --
    outside every table, or on the cells beside one -- describe that cohort's
    data, not the format, so a template drops them (reported)."""
    from openpyxl.formatting.formatting import ConditionalFormattingList
    if not ws.conditional_formatting:
        return
    animal_tables = [t for t in ts if t.id_col]
    if not animal_tables:
        return

    def belongs(rng: str) -> bool:
        m = _REF.match(rng)
        if not m or not m.group("c1"):
            return True
        c = column_index_from_string(m.group("c1").lstrip("$"))
        return any(t.first_col <= c <= t.last_col and c not in t.loose_cols for t in animal_tables)

    new, dropped = ConditionalFormattingList(), []
    for cf in ws.conditional_formatting:
        keep = [r for r in str(cf.sqref).split() if belongs(r)]
        dropped += [r for r in str(cf.sqref).split() if not belongs(r)]
        if keep:
            for rule in cf.rules:
                new.add(" ".join(keep), rule)
    if dropped:
        ws.conditional_formatting = new
        rep.add("[%s] colour rules on cells outside the tables dropped: %s"
                % (ws.title, ", ".join(dropped[:12]) + (" ..." if len(dropped) > 12 else "")))


def template_info(wb) -> Dict[str, str]:
    if INFO_SHEET not in wb.sheetnames:
        raise ValueError("this workbook is not a template (no %s sheet); make one with "
                         "'mousedb sheet-template make'" % INFO_SHEET)
    ws = wb[INFO_SHEET]
    return {str(ws.cell(r, 1).value): str(ws.cell(r, 2).value) for r in range(2, ws.max_row + 1)}


# ---------------------------------------------------------------------------
# building a new sheet
# ---------------------------------------------------------------------------

_REF = re.compile(r"^(?P<sheet>(?:'(?:[^']|'')+'|[^'!]+)!)?"
                  r"(?P<c1>\$?[A-Z]{1,3})?(?P<r1>\$?\d+)?"
                  r"(?::(?P<c2>\$?[A-Z]{1,3})?(?P<r2>\$?\d+)?)?$")


@dataclass
class _Place:
    """Where a template row went: ('animal', group, animal, k) / ('plain', row)
    / ('header', row) / ('loose', row)."""
    kind: str
    group: int = -1
    animal: str = ""
    k: int = 0


def _first_row(t: Table) -> int:
    """Where a table's rows after its header start: the first row of its
    sequence as it stands in the template. WHY not "the row after the header":
    a table beside another may have no header row of its own, and its rows
    must stay level with the rows they sit beside."""
    kind, x = t.sequence[0]
    return x if kind == "plain" else next(iter(x.rows.values()))[0]


class _Layout:
    """For every tab: template row -> its role, and role -> output row."""

    def __init__(self, wb, ids, model: str, animals: List[str]):
        self.ids, self.model, self.animals = ids, model, animals
        self.tables = _workbook_tables(wb, ids)
        self.role: Dict[Tuple[str, int, int], _Place] = {}       # (tab, table#, row)
        self.out: Dict[Tuple[str, int], Dict] = {}               # (tab, table#) -> key -> out row
        self.dropped: List[str] = []
        for tab, ts in self.tables.items():
            for ti, t in enumerate(ts):
                if t.id_col is None:
                    continue
                m: Dict = {}
                r_out = _first_row(t)
                for h in t.header_rows:
                    self.role[(tab, ti, h)] = _Place("header")
                    m[("header", h)] = h
                gi = 0
                for kind, x in t.sequence:
                    if kind == "plain":
                        self.role[(tab, ti, x)] = _Place("plain", group=x)
                        m[("plain", x)] = r_out
                        r_out += 1
                        continue
                    for a, rows in x.rows.items():
                        for k, r in enumerate(rows):
                            self.role[(tab, ti, r)] = _Place("animal", gi, a, k)
                    model_rows = x.rows.get(model)
                    if not model_rows:
                        self.dropped.append("%s: a group starting at row %d (no %s rows)"
                                            % (tab, next(iter(x.rows.values()))[0], model))
                    else:
                        for new in animals:
                            for k in range(len(model_rows)):
                                m[("animal", gi, new, k)] = r_out
                                r_out += 1
                    gi += 1
                self.out[(tab, ti)] = m

    def table_of(self, tab: str, col: int) -> Optional[int]:
        for ti, t in enumerate(self.tables.get(tab, [])):
            if t.first_col <= col <= t.last_col:
                return ti
        return None

    def first_last(self, tab, ti, gi, k_first, k_last) -> Tuple[Optional[int], Optional[int]]:
        m = self.out[(tab, ti)]
        return m.get(("animal", gi, self.animals[0], k_first)), m.get(("animal", gi, self.animals[-1], k_last))

    def map_row(self, tab, col, row, target: Optional[str], source: Optional[str]):
        """Output row for a reference to (tab, col, row), seen from a row being
        written for new animal ``target`` copied from template animal ``source``.
        None when it cannot be re-pointed."""
        ti = self.table_of(tab, col)
        if ti is None or (tab, ti) not in self.out:
            return row                                   # a fixed table: unchanged
        if col in self.tables[tab][ti].loose_cols:
            return row                                   # a cell beside the table: stays put
        p = self.role.get((tab, ti, row))
        if p is None:
            return row                                   # beyond the table: unchanged
        m = self.out[(tab, ti)]
        if p.kind == "header":
            return row
        if p.kind == "plain":
            return m.get(("plain", row))
        if p.kind == "loose":
            return row
        if target is not None and p.animal == source:
            return m.get(("animal", p.group, target, p.k))
        return None


def _split_sheet(prefix: str) -> Optional[str]:
    if not prefix:
        return None
    name = prefix[:-1]
    if name.startswith("'"):
        name = name[1:-1].replace("''", "'")
    return name


def _repoint(formula: str, tab: str, lay: _Layout, target, source, problems: List[str],
             where: str) -> str:
    """``formula`` with every cell reference re-pointed (see module docstring)."""
    tok = Tokenizer(formula)
    out = []
    for t in tok.items:
        if t.type == "OPERAND" and t.subtype == "RANGE":
            out.append(_repoint_ref(t.value, tab, lay, target, source, problems, where))
        else:
            out.append(t.value)
    return "=" + "".join(out)


def _repoint_ref(ref: str, tab: str, lay: _Layout, target, source, problems, where) -> str:
    m = _REF.match(ref)
    if not m or (m.group("r1") is None and m.group("r2") is None):
        return ref                                   # a name, or whole columns: unchanged
    sheet = _split_sheet(m.group("sheet")) or tab
    c1, r1, c2, r2 = m.group("c1"), m.group("r1"), m.group("c2"), m.group("r2")
    if c1 is None:
        return ref                                   # whole rows: leave as written

    def num(r):
        return int(r.lstrip("$"))

    def put(r, new):
        return ("$" if r.startswith("$") else "") + str(new)

    col1 = column_index_from_string(c1.lstrip("$"))
    n1 = lay.map_row(sheet, col1, num(r1), target, source)
    if r2 is None:
        if n1 is None:
            problems.append("%s: %s points at another animal's row; left as written" % (where, ref))
            return ref
        return (m.group("sheet") or "") + c1 + put(r1, n1)
    col2 = column_index_from_string((c2 or c1).lstrip("$"))
    n2 = lay.map_row(sheet, col2, num(r2), target, source)
    if n1 is None or n2 is None:
        ti = lay.table_of(sheet, col1)
        p1 = lay.role.get((sheet, ti, num(r1)))
        p2 = lay.role.get((sheet, ti, num(r2)))
        if p1 and p2 and p1.kind == p2.kind == "animal" and p1.group == p2.group:
            n1, n2 = lay.first_last(sheet, ti, p1.group, p1.k, p2.k)
        if n1 is None or n2 is None:
            problems.append("%s: %s spans rows that cannot be re-pointed; left as written" % (where, ref))
            return ref
    return (m.group("sheet") or "") + c1 + put(r1, n1) + ":" + (c2 or c1) + put(r2, n2)


def _copy_style(src, dst) -> None:
    if src.has_style:
        dst.font = copy.copy(src.font)
        dst.fill = copy.copy(src.fill)
        dst.border = copy.copy(src.border)
        dst.alignment = copy.copy(src.alignment)
        dst.number_format = src.number_format
        dst.protection = copy.copy(src.protection)


def _remap_conditional_formats(ws, tab: str, lay: "_Layout", problems: List[str]) -> None:
    """Colour rules follow the rows they colour. A rule over one block of
    animal rows (a summary block) is re-pointed like a range in a formula;
    whole-column rules stay as written."""
    from openpyxl.formatting.formatting import ConditionalFormattingList
    old = ws.conditional_formatting
    new = ConditionalFormattingList()
    for cf in old:
        parts = []
        for rng in str(cf.sqref).split():
            # Only a range that could NOT be re-pointed is reported; one that
            # comes out the same (as many new animals as the template had) is fine.
            failed: List[str] = []
            parts.append(_repoint_ref(rng, tab, lay, None, None, failed, ""))
            if failed:
                problems.append("%s: colour rule on %s kept as written" % (tab, rng))
        for rule in cf.rules:
            new.add(" ".join(parts), rule)
    ws.conditional_formatting = new


def build_workbook(template, cohort_id: str, animals: Sequence[str]):
    """The new cohort's workbook (not saved) and the list of problems found.
    ``animals``: the new subject ids in order (e.g. PROJA_07_01 ...)."""
    animals = list(animals)
    if not animals:
        raise ValueError("no animals given")
    wb = openpyxl.load_workbook(template)
    info = template_info(wb)
    ref_cohort, model = info["reference_cohort"], info["model_animal"]
    ids = _id_regex(ref_cohort)
    lay = _Layout(wb, ids, model, animals)
    problems: List[str] = list("left out: " + d for d in lay.dropped)
    for tab, ts in lay.tables.items():
        ws = wb[tab]
        for ti, t in enumerate(ts):
            if t.id_col is None:
                continue
            m = lay.out[(tab, ti)]
            # read everything the table holds before rewriting it
            src = {(r, c): ws.cell(r, c) for r in range(1, ws.max_row + 1)
                   for c in range(t.first_col, t.last_col + 1)}
            snap = {k: (v.value, copy.copy(v._style)) for k, v in src.items()}
            for r in range(_first_row(t), ws.max_row + 1):
                for c in range(t.first_col, t.last_col + 1):
                    ws.cell(r, c).value = None

            def write(r_out, r_src, target, source):
                for c in range(t.first_col, t.last_col + 1):
                    if c in t.loose_cols:
                        continue
                    v, style = snap.get((r_src, c), (None, None))
                    cell = ws.cell(r_out, c)
                    if style is not None:
                        cell._style = copy.copy(style)
                    if c == t.id_col and target is not None:
                        cell.value = target
                    elif _is_formula(v):
                        cell.value = _repoint(v, tab, lay, target, source, problems,
                                              "%s!%s%d" % (tab, get_column_letter(c), r_out))
                    elif isinstance(v, str) and target is not None:
                        cell.value = v.replace(ref_cohort, cohort_id)
                    else:
                        cell.value = v

            for kind, x in t.sequence:
                if kind == "plain":
                    write(m[("plain", x)], x, None, None)
            gi = 0
            for kind, x in t.sequence:
                if kind != "group":
                    continue
                model_rows = x.rows.get(model) or []
                for new in animals:
                    for k, r_src in enumerate(model_rows):
                        write(m[("animal", gi, new, k)], r_src, new, model)
                gi += 1
            for c in t.loose_cols:
                for (r, cc), (v, style) in snap.items():
                    if cc != c or v is None:
                        continue
                    cell = ws.cell(r, c)
                    cell._style = copy.copy(style)
                    cell.value = (_repoint(v, tab, lay, None, None, problems, "%s!%s%d" % (tab, get_column_letter(c), r))
                                  if _is_formula(v) else v)
        # Tables with no animal rows (a planning tab, a block of totals beside
        # a table) stay where they are, but their formulas may point INTO
        # animal rows (a mean over every animal's day 0): re-point those too.
        fixed_cols = [(t.first_col, t.last_col) for t in ts if t.id_col is None]
        if not ts:
            fixed_cols = [(1, ws.max_column)]
        for a, b in fixed_cols:
            for r in range(1, ws.max_row + 1):
                for c in range(a, b + 1):
                    v = ws.cell(r, c).value
                    if _is_formula(v):
                        ws.cell(r, c).value = _repoint(v, tab, lay, None, None, problems,
                                                       "%s!%s%d" % (tab, get_column_letter(c), r))
        if any(t.id_col for t in ts):
            _remap_conditional_formats(ws, tab, lay, problems)
        # ids and the cohort id in tabs without animal rows
        if not any(t.id_col for t in ts):
            for row in ws.iter_rows():
                for c in row:
                    if isinstance(c.value, str) and ref_cohort in c.value and not _is_formula(c.value):
                        c.value = c.value.replace(ref_cohort, cohort_id)
    del wb[INFO_SHEET]
    return wb, problems


