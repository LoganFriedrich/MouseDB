TEMPLATE_DIR = "sheet_templates"          # under <mousedb_root>/config/


def parse_animals(text, cohort_id: str) -> List[str]:
    """Subject numbers as typed -> subject ids, in order.

    "01-16" -> PROJA_07_01 .. PROJA_07_16; "3,4,16,17,19" -> those five. Ranges
    and lists mix ("1-4, 9"). WHY a list and not a count: a cohort's animals
    need not be numbered from 1 -- animals moved in from another cohort keep
    the numbers they were given."""
    from .cohort_tools.make_sheets import NewSheetRefused
    nums: List[int] = []
    for part in str(text or "").replace(" ", "").split(","):
        if not part:
            continue
        m = re.fullmatch(r"(\d{1,2})(?:-(\d{1,2}))?", part)
        if not m:
            raise NewSheetRefused("'%s' is not a subject number or range (for example 01-16, "
                                  "or 3,4,16,17,19)" % part)
        a, b = int(m.group(1)), int(m.group(2) or m.group(1))
        if not 1 <= a <= b <= 99:
            raise NewSheetRefused("'%s': subject numbers run from 1 to 99, low to high" % part)
        nums.extend(range(a, b + 1))
    if not nums:
        raise NewSheetRefused("no subject numbers given (for example 01-16, or 3,4,16,17,19)")
    if len(set(nums)) != len(nums):
        raise NewSheetRefused("a subject number is given twice: %s" % text)
    return ["%s_%02d" % (cohort_id, n) for n in nums]


def cohort_of(text):
    """(SheetProject, cohort id) for a typed cohort name, or NewSheetRefused.
    The WHOLE text must be a configured project, one underscore and two digits:
    the name decides which file is written in the sheets folder."""
    from . import sheet_projects
    from .cohort_tools.make_sheets import NewSheetRefused
    t = str(text or "").strip().upper()
    projects = sheet_projects.definitions()
    m = re.fullmatch(r"([A-Z]+)_([0-9]{2})", t)
    if not m:
        raise NewSheetRefused("'%s' is not a cohort name: give the project and the two-digit "
                              "cohort number, for example %s_07"
                              % (str(text or "").strip(), next(iter(projects), "PROJA")))
    p = projects.get(m.group(1))
    if p is None:
        raise NewSheetRefused("%s is not a project with sheets here (%s), so a workbook made "
                              "for it would never be read. Add it first: %s"
                              % (m.group(1), ", ".join(projects) or "none set",
                                 sheet_projects.SET_COMMAND))
    return p, t


def refuse_if_cohort_has_a_workbook(folder, cohort_id: str) -> None:
    """NewSheetRefused if ``folder`` holds a file read as this cohort's sheet,
    or one that LOOKS like it (a copy, a variant, the number without its
    zero): an empty new workbook beside a real one would be imported in its
    place as the newest. A folder that cannot be listed is a refusal too."""
    from . import sheet_projects
    from .cohort_tools.make_sheets import NewSheetRefused
    folder = Path(folder)
    try:
        names = sorted(os.listdir(folder))
    except FileNotFoundError:
        return
    except OSError as e:
        raise NewSheetRefused("cannot list %s to make sure %s has no workbook there yet (%s)."
                              % (folder, cohort_id, e)) from None
    p = sheet_projects.project_of(cohort_id)
    number = int(cohort_id.rsplit("_", 1)[1])
    like = re.compile(r"%s0*%d%s.*\.xls[xm]?$" % (re.escape(p.head), number, re.escape(p.rest)), re.I)
    hits = [n for n in names if sheet_projects.match(n)[0] == cohort_id or like.search(n)]
    if hits:
        raise NewSheetRefused(
            "%s already has a workbook in %s: %s. A new sheet is never written over an existing "
            "one or beside it -- an empty file there would replace the real sheet, or be read "
            "in its place as the newest file. If you meant a new cohort, use its own number. "
            "If %s really needs a fresh sheet, move the existing file(s) out of that folder first."
            % (cohort_id, folder, ", ".join(hits), cohort_id))


def template_path(project) -> Path:
    """The project's template, or NewSheetRefused saying how to make one."""
    from .cohort_tools.make_sheets import NewSheetRefused
    how = ("mousedb sheet-template make %s <a %s cohort's workbook> --cohort %s_NN"
           % (project.project, project.project, project.project))
    if project.template is None:
        raise NewSheetRefused("project %s has no template yet, so its new sheets cannot be laid "
                              "out. Make one from a cohort sheet the lab is happy with: %s"
                              % (project.project, how))
    if not project.template.is_file():
        raise NewSheetRefused("project %s's template %s is not there (moved or deleted?). Make it "
                              "again: %s" % (project.project, project.template, how))
    return project.template


def build_sheet(cohort_text, animals_text, sheets_dir) -> Tuple[Path, List[str]]:
    """Make the new cohort's workbook in ``sheets_dir`` from its project's
    template: (the file written, the problems listed while re-pointing).
    Refused (NewSheetRefused, nothing written) for an unknown project, a
    project with no template, a malformed animal list, or a cohort that
    already has a workbook there -- checked first and again just before the
    save, which itself never replaces a file."""
    from .cohort_tools.make_sheets import NewSheetRefused, _save_workbook_no_clobber
    project, cohort_id = cohort_of(cohort_text)
    animals = parse_animals(animals_text, cohort_id)
    tpl = template_path(project)
    sheets_dir = Path(sheets_dir)
    if not sheets_dir.is_dir():
        raise NewSheetRefused("the sheets folder %s is not there (moved, renamed, or its drive "
                              "is offline)" % sheets_dir)
    refuse_if_cohort_has_a_workbook(sheets_dir, cohort_id)
    wb, problems = build_workbook(tpl, cohort_id, animals)
    target = sheets_dir / project.file_name(cohort_id.rsplit("_", 1)[1])
    refuse_if_cohort_has_a_workbook(sheets_dir, cohort_id)
    try:
        _save_workbook_no_clobber(wb, target)
    except FileExistsError:
        raise NewSheetRefused("%s appeared in %s while the sheet was being built; nothing was "
                              "written" % (target.name, sheets_dir)) from None
    return target, problems


def make_project_template(project_code: str, reference, cohort_id: str,
                          keep: Optional[Dict[str, Sequence[str]]] = None) -> Tuple[Path, Report]:
    """Make ``project_code``'s template from ``reference`` (one of its cohort
    workbooks, only read) into <lab settings folder>/sheet_templates/, write
    the report beside it, and record it in the lab settings as the project's
    template. An earlier template is kept, renamed with the time it was
    replaced: a template is never overwritten."""
    from . import sheet_projects
    project = sheet_projects.definitions().get(str(project_code).upper())
    if project is None:
        raise ValueError("%s is not a project with sheets; set its sheet name first: %s"
                         % (project_code, sheet_projects.SET_COMMAND))
    if not re.fullmatch(r"%s_\d{2}" % re.escape(project.project), str(cohort_id).upper()):
        raise ValueError("--cohort must be the %s cohort the reference workbook belongs to, "
                         "such as %s_05" % (project.project, project.project))
    folder = sheet_projects.config_path().parent / TEMPLATE_DIR
    folder.mkdir(parents=True, exist_ok=True)
    out = folder / ("%s.xlsx" % project.project)
    if out.exists():
        stamp = datetime.now().strftime("%Y-%m-%d_%H%M%S")
        out.rename(folder / ("%s_replaced_%s.xlsx" % (project.project, stamp)))
    rep = make_template(reference, str(cohort_id).upper(), out, keep)
    (folder / ("%s_template_report.txt" % project.project)).write_text(rep.text(), encoding="utf-8")
    sheet_projects.set_project(project.project, project.sheet_name,
                               template="%s/%s" % (TEMPLATE_DIR, out.name))
    return out, rep
